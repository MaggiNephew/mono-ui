def qt_palette_groups(t: Tokens) -> dict[str, dict[str, Color]]:
    return {g: {r: t.color(v) for r, v in roles.items()} for g, roles in QT_GROUPS.items()}


def qt6ct(t: Tokens, o: Path) -> Path:
    groups = qt_palette_groups(t)
    lines = ["[ColorScheme]"]
    for g in ("active", "disabled", "inactive"):
        lines.append(f"{g}_colors=" + ", ".join(groups[g][r].argb8 for r in QT_ROLES))
    p = o / "qt6ct" / "colors" / "mono-dark.conf"
    write(p, "\n".join(lines) + "\n")
    return p


# ---------- KDE colour scheme (MonoBW) ----------

def _kde_set(t: Tokens, bg_alt: str, bg: str, hover: str, fg_inactive: str, fg: str = "gray.1000",
             fg_active: str = "gray.1000", visited: str = "gray.800") -> list[str]:
    c = lambda x: t.color(x).rgb_csv
    return [
        f"BackgroundAlternate={c(bg_alt)}", f"BackgroundNormal={c(bg)}",
        f"DecorationFocus={c('gray.650')}", f"DecorationHover={c(hover)}",
        f"ForegroundActive={c(fg_active)}", f"ForegroundInactive={c(fg_inactive)}",
        f"ForegroundLink={c('gray.1000')}", f"ForegroundNegative={c(fg)}", f"ForegroundNeutral={c(fg)}",
        f"ForegroundNormal={c(fg)}", f"ForegroundPositive={c(fg)}", f"ForegroundVisited={c(visited)}",
    ]


def kde_scheme(t: Tokens, o: Path) -> Path:
    c = lambda x: t.color(x).rgb_csv
    out: list[str] = [
        "[ColorEffects:Disabled]", f"Color={c('gray.100')}", "ColorAmount=0", "ColorEffect=0",
        "ContrastAmount=0.55", "ContrastEffect=1", "IntensityAmount=0.1", "IntensityEffect=2", "",
        "[ColorEffects:Inactive]", "ChangeSelectionColor=false", "Enable=false", "",
    ]
    std = dict(bg_alt="gray.150", bg="gray.100", hover="gray.800", fg_inactive="gray.650")
    sections = [
        ("[Colors:Window]", std),
        ("[Colors:View]", std),
        ("[Colors:Button]", dict(bg_alt="gray.250", bg="gray.200", hover="gray.800", fg_inactive="gray.650")),
        ("[Colors:Header]", std),
        ("[Colors:Header][Inactive]", dict(std, fg="gray.900", fg_active="gray.900")),
        ("[Colors:Tooltip]", dict(bg_alt="gray.250", bg="gray.200", hover="gray.800", fg_inactive="gray.650")),
        ("[Colors:Complementary]", std),
        ("[Colors:Selection]", dict(bg_alt="#303030", bg="gray.350", hover="#6e6e6e", fg_inactive="gray.800")),
    ]
    for head, kw in sections:
        out.append(head)
        out += _kde_set(t, **kw)
        out.append("")
    out += [
        "[WM]", f"activeBackground={c('gray.100')}", f"activeBlend={c('gray.1000')}",
        f"activeForeground={c('gray.1000')}", f"inactiveBackground={c('gray.100')}",
        f"inactiveBlend={c('gray.650')}", f"inactiveForeground={c('gray.650')}", "",
        "[General]", "ColorScheme=MonoBW", "Name=Mono Black & White",
    ]
    p = o / "color-schemes" / "MonoBW.colors"
    write(p, "\n".join(out) + "\n")
    return p


# ---------- terminals ----------

def terminals(t: Tokens, o: Path) -> list[Path]:
    term = t.terminal()
    a = term["ansi"]
    kitty = [f"# {HEADER}", "# kitty: add `include mono-colors.conf` to kitty.conf and remove the colour lines there",
             f"background {term['background'].hex}", f"foreground {term['foreground'].hex}"]
    kitty += [f"color{i:<2} {c.hex}" for i, c in enumerate(a)]
    kitty += [f"selection_foreground {term['selectionFg'].hex}", f"selection_background {term['selectionBg'].hex}",
              f"cursor {term['cursor'].hex}", f"cursor_text_color {term['cursorText'].hex}",
              f"tab_bar_background {term['background'].hex}",
              f"active_tab_background {term['tabActiveBg'].hex}", f"active_tab_foreground {term['tabActiveFg'].hex}",
              f"inactive_tab_background {term['tabInactiveBg'].hex}", f"inactive_tab_foreground {term['tabInactiveFg'].hex}"]
    p1 = o / "kitty" / "mono-colors.conf"
    write(p1, "\n".join(kitty) + "\n")

    foot = [f"# {HEADER}", "# foot: replace the [colors-dark] section of foot.ini with this one", "[colors-dark]",
            f"background={term['backgroundAlt'].hex[1:]}", f"foreground={term['foreground'].hex[1:]}"]
    foot += [f"regular{i}={c.hex[1:]}" for i, c in enumerate(a[:8])]
    foot += [f"bright{i}={c.hex[1:]}" for i, c in enumerate(a[8:])]
    foot += [f"selection-foreground={term['selectionFg'].hex[1:]}", f"selection-background={term['selectionBg'].hex[1:]}"]
    p2 = o / "foot" / "mono-colors.ini"
    write(p2, "\n".join(foot) + "\n")
    return [p1, p2]


def starship(t: Tokens, o: Path) -> Path:
    s = t.rice("starship")
    lines = [f"# {HEADER}", "# paste over the [palettes.mono] table in starship.toml", "[palettes.mono]"]
    lines += [f"{k} = '{c.hex}'" for k, c in s.items()]
    p = o / "starship" / "palette.toml"
    write(p, "\n".join(lines) + "\n")
    return p


def hypr_look(t: Tokens, o: Path) -> Path:
    h = t.rice("hyprland")
    rgba = lambda c: f"rgba({c.hex8[1:]})"
    text = f"""-- {HEADER}
-- Window look from the tokens. In hyprland.lua:  local mono = dofile(os.getenv("HOME") .. "/.config/hypr/mono-look.lua")
-- then use mono.active_border, mono.rounding, ... in hl.config.
return {{
    active_border   = "{rgba(h['activeBorder'])}",
    inactive_border = "{rgba(h['inactiveBorder'])}",
    shadow          = "{rgba(h['shadow'])}",
    border_size     = {h['borderSize']},
    rounding        = {h['rounding']},
    gaps_in         = {h['gapsIn']},
    gaps_out        = {h['gapsOut']},
}}
"""
    p = o / "hypr" / "mono-look.lua"
    write(p, text)
    return p


def bar_palette(t: Tokens, o: Path) -> Path:
    b = t.rice("bar")
    lines = [f"// {HEADER}", "// The palette at the top of quickshell/shell.qml (lines 25-33), from the tokens."]
    lines += [f"    readonly property color {k + ':':<10} \"{c.hex}\"" for k, c in b.items()]
    p = o / "quickshell" / "bar-palette.qml.txt"
    write(p, "\n".join(lines) + "\n")
    return p
