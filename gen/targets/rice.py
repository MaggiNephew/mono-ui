"""Your desktop: the files matugen and you maintain today, regenerated from tokens.

Every file here keeps the exact format of the one in magginephew-rice, so it's
a drop-in replacement. `gen/install-rice.sh` copies them over with a backup.
"""
from __future__ import annotations

from pathlib import Path

from tokens import HEADER, Color, Tokens, write


def build(t: Tokens, out: Path) -> list[Path]:
    o = out / "rice"
    files: list[Path] = []
    files += matugen_files(t, o)
    files.append(qt6ct(t, o))
    files.append(kde_scheme(t, o))
    files += terminals(t, o)
    files.append(starship(t, o))
    files.append(hypr_look(t, o))
    files.append(bar_palette(t, o))
    return files


# ---------- matugen formats (hypr/colors.lua, quickshell/colors.qml) ----------

def matugen_files(t: Tokens, o: Path) -> list[Path]:
    m = t.rice("matugen")
    lua = ["-- generated by matugen (monochrome) -- do not edit by hand", "return {"]
    for k, c in m.items():
        lua.append(f"    {k:<11} = \"rgba({c.r}, {c.g}, {c.b}, 1)\",")
    lua.append("}")
    p1 = o / "hypr" / "colors.lua"
    write(p1, "\n".join(lua) + "\n")

    camel = {"bg_dim": "bgDim", "fg_muted": "fgMuted", "on_primary": "onPrimary"}
    qml = ["// generated by matugen (monochrome) -- do not edit by hand", "pragma Singleton", "",
           "import QtQuick", "", "QtObject {"]
    for k, c in m.items():
        name = camel.get(k, k)
        qml.append(f"    readonly property color {name + ':':<11} \"{c.hex}\"")
    qml.append("}")
    p2 = o / "quickshell" / "colors.qml"
    write(p2, "\n".join(qml) + "\n")
    return [p1, p2]


